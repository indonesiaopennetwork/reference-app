#!/usr/bin/env bash
# scripts/merge-tbls-docs.sh <tbls-doc-dir> <output.md>
#
# tbls writes a README.md plus one public.<table>.md per table. This merges
# them into a single Markdown file: the README first, then every table (in
# the README's order) as a "## public.<table>" section, with the cross-file
# links rewritten to in-page anchors. Used by `task docs:db`.
set -euo pipefail

SRC="$1"
OUT="$2"
FOOTER='> Generated by [tbls](https://github.com/k1LoW/tbls)'

# public.foo_bar.md -> #publicfoo_bar (GitHub's anchor for "## public.foo_bar")
relink() { sed -E 's/\]\((public\.[a-z0-9_]+)\.md\)/](#\1)/g; s/\]\(#public\.([a-z0-9_]+)\)/](#public\1)/g'; }

{
  grep -vF "$FOOTER" "$SRC/README.md" | relink

  # Table pages in the order the README's "Tables" list links them.
  grep -oE '^\| \[public\.[a-z0-9_]+\]\(public\.[a-z0-9_]+\.md\)' "$SRC/README.md" \
    | sed -E 's/.*\((public\.[a-z0-9_]+\.md)\)/\1/' \
    | while read -r page; do
        echo
        # Demote one level: "# public.x" -> "## public.x", "## Columns" -> "### Columns".
        grep -vF "$FOOTER" "$SRC/$page" | sed -E 's/^(#+) /#\1 /' | relink
      done

  echo
  echo "---"
  echo
  echo "$FOOTER"
} | cat -s > "$OUT"
